students = [
    {"name": "가", "scores": [90, 80]},
    {"name": "나", "scores": [70, 60, 50]},
    {"name": "다", "scores": []},
    {"name": "라", "scores": [100]},
]


def average(scores):
    if not scores:
        return "측정불가"
    return sum(scores) / len(scores)


for st in students:
    print(st["name"], average(st["scores"]))
