#   반면 average 함수만 떼어 주면 "라" 학생의 문제는 절대 찾지 못합니다.
#   → 최소 재현 예제란 "짧게 자른 코드"가 아니라
#     "오류가 재현되는 가장 짧은 전체"입니다.
